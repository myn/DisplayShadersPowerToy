# Complete Production Automation Script
# This script handles the entire production build, test, and package process

param(
    [Parameter(Mandatory=$false)]
    [ValidateSet("ClearType", "Full", "Both")]
    [string]$Mode = "ClearType",
    
    [Parameter(Mandatory=$false)]
    [switch]$SkipTests,
    
    [Parameter(Mandatory=$false)]
    [switch]$CreatePackage,
    
    [Parameter(Mandatory=$false)]
    [string]$Version = "2.0.0"
)

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$Banner = @"
????????????????????????????????????????????????????????????????
?                                                              ?
?   Display Shaders PowerToy - Production Build & Package     ?
?                                                              ?
????????????????????????????????????????????????????????????????
"@

Write-Host $Banner -ForegroundColor Cyan
Write-Host ""
Write-Host "Mode: $Mode" -ForegroundColor White
Write-Host "Version: $Version" -ForegroundColor White
Write-Host ""

$StartTime = Get-Date

# Step 1: Clean previous builds
Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host "[Step 1/5] Cleaning Previous Builds" -ForegroundColor Cyan
Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host ""

if (Test-Path "bin") {
    Remove-Item "bin" -Recurse -Force
    Write-Host "  ? Removed bin folder" -ForegroundColor Green
}

if (Test-Path "obj") {
    Remove-Item "obj" -Recurse -Force
    Write-Host "  ? Removed obj folder" -ForegroundColor Green
}

if (Test-Path "dist") {
    Remove-Item "dist" -Recurse -Force
    Write-Host "  ? Removed dist folder" -ForegroundColor Green
}

Write-Host ""

# Step 2: Build C# Application
Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host "[Step 2/5] Building C# Application" -ForegroundColor Cyan
Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
Write-Host ""

$buildOutput = dotnet build --configuration Release --verbosity minimal 2>&1

if ($LASTEXITCODE -eq 0) {
    Write-Host "  ? C# project built successfully" -ForegroundColor Green
    $CSharpBuildSuccess = $true
} else {
    Write-Host "  ? C# build failed!" -ForegroundColor Red
    Write-Host $buildOutput
    exit 1
}

# Step 3: Build Native DLL (if Full or Both mode)
$NativeBuildSuccess = $false

if ($Mode -eq "Full" -or $Mode -eq "Both") {
    Write-Host ""
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host "[Step 3/5] Building Native C++ DLL" -ForegroundColor Cyan
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host ""
    
    # Check if MSBuild is available
    $msbuild = & "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe" `
        -latest -requires Microsoft.Component.MSBuild -find MSBuild\**\Bin\MSBuild.exe `
        -prerelease 2>$null | Select-Object -First 1
    
    if ($msbuild) {
        Write-Host "  Using MSBuild: $msbuild" -ForegroundColor Gray
        
        try {
            & $msbuild "Native\DisplayShaderHook\DisplayShaderHook.vcxproj" `
                /p:Configuration=Release `
                /p:Platform=x64 `
                /verbosity:minimal `
                /nologo
            
            if ($LASTEXITCODE -eq 0) {
                Write-Host "  ? Native DLL built successfully" -ForegroundColor Green
                $NativeBuildSuccess = $true
                
                # Copy DLL to C# output
                $dllSource = "bin\x64\Release\DisplayShaderHook.dll"
                $dllDest = "bin\Release\net8.0-windows\DisplayShaderHook.dll"
                
                if (Test-Path $dllSource) {
                    Copy-Item $dllSource $dllDest -Force
                    Write-Host "  ? DLL copied to C# output directory" -ForegroundColor Green
                }
            } else {
                Write-Host "  ? Native DLL build failed" -ForegroundColor Red
                if ($Mode -eq "Full") {
                    exit 1
                } else {
                    Write-Host "  ? Continuing with ClearType mode only" -ForegroundColor Yellow
                }
            }
        } catch {
            Write-Host "  ? Native build error: $($_.Exception.Message)" -ForegroundColor Red
            if ($Mode -eq "Full") {
                exit 1
            }
        }
    } else {
        Write-Host "  ? MSBuild not found - skipping native build" -ForegroundColor Yellow
        Write-Host "    Install Visual Studio 2022 with C++ Desktop Development workload" -ForegroundColor Gray
        if ($Mode -eq "Full") {
            Write-Host "  ? Cannot build in Full mode without C++ toolchain" -ForegroundColor Red
            exit 1
        }
    }
} else {
    Write-Host ""
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host "[Step 3/5] Skipping Native C++ Build (ClearType mode)" -ForegroundColor Cyan
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host ""
}

# Step 4: Run Tests
if (-not $SkipTests) {
    Write-Host ""
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host "[Step 4/5] Running Production Tests" -ForegroundColor Cyan
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host ""
    
    if (Test-Path "test-production.ps1") {
        try {
            & ".\test-production.ps1" -Configuration Release
            Write-Host ""
        } catch {
            Write-Host "  ? Tests failed but continuing..." -ForegroundColor Yellow
        }
    } else {
        Write-Host "  ? Test script not found" -ForegroundColor Yellow
    }
} else {
    Write-Host ""
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host "[Step 4/5] Skipping Tests (--SkipTests flag)" -ForegroundColor Cyan
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host ""
}

# Step 5: Create Distribution Package
if ($CreatePackage) {
    Write-Host ""
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host "[Step 5/5] Creating Distribution Package" -ForegroundColor Cyan
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host ""
    
    $distFolder = "dist"
    $packageName = if ($NativeBuildSuccess) {
        "DisplayShadersPowerToy-v$Version-Full"
    } else {
        "DisplayShadersPowerToy-v$Version-ClearType"
    }
    
    $packageFolder = Join-Path $distFolder $packageName
    
    # Create dist folders
    New-Item -ItemType Directory -Path $packageFolder -Force | Out-Null
    
    # Copy files
    Write-Host "  Copying files..." -ForegroundColor Gray
    
    $sourceFiles = Get-ChildItem "bin\Release\net8.0-windows" -File
    foreach ($file in $sourceFiles) {
        Copy-Item $file.FullName $packageFolder -Force
    }
    
    # Copy SubpixelMasks if exists
    if (Test-Path "bin\Release\net8.0-windows\SubpixelMasks") {
        Copy-Item "bin\Release\net8.0-windows\SubpixelMasks" $packageFolder -Recurse -Force
    }
    
    # Copy documentation
    $docs = @("README.md", "LICENSE", "GETTING_STARTED.md", "FAQ.md", "CHANGELOG.md")
    foreach ($doc in $docs) {
        if (Test-Path $doc) {
            Copy-Item $doc $packageFolder -Force
        }
    }
    
    Write-Host "  ? Files copied to package folder" -ForegroundColor Green
    
    # Create README for package
    $packageReadme = @"
# Display Shaders PowerToy v$Version

$(if ($NativeBuildSuccess) { "**Mode**: Full Shader Support" } else { "**Mode**: ClearType Mode Only" })

## Installation

1. Extract all files to a folder (e.g., C:\Program Files\DisplayShadersPowerToy)
2. Run DisplayShadersPowerToy.exe $(if ($NativeBuildSuccess) { "as Administrator" } else { "" })
3. Select your display's subpixel layout
4. Click "Apply"

## Requirements

- Windows 10/11 (x64)
- .NET 8.0 Runtime (included)
$(if ($NativeBuildSuccess) { "- Administrator privileges (for DLL injection)" } else { "" })

## Features

$(if ($NativeBuildSuccess) {
@"
- ? Real DirectWrite/D3D shader hooks
- ? WOLED WRGB fix (Blue in middle)
- ? QD-OLED triangular fix (vertical fringing)
- ? ClearType fallback mode
"@
} else {
@"
- ? ClearType optimization presets
- ? WOLED/QD-OLED workarounds
- ? Settings persistence
- ? Note: This version does not include native shader support
  - Build from source for full shader features
"@
})

## Documentation

- Getting Started: See GETTING_STARTED.md
- FAQ: See FAQ.md
- Full documentation: https://github.com/yourusername/DisplayShadersPowerToy

## Support

- Issues: https://github.com/yourusername/DisplayShadersPowerToy/issues
- Discussions: https://github.com/yourusername/DisplayShadersPowerToy/discussions

---

Built: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
"@
    
    Set-Content -Path (Join-Path $packageFolder "README.txt") -Value $packageReadme
    
    # Create ZIP
    Write-Host "  Creating ZIP archive..." -ForegroundColor Gray
    $zipPath = Join-Path $distFolder "$packageName.zip"
    Compress-Archive -Path "$packageFolder\*" -DestinationPath $zipPath -Force
    
    Write-Host "  ? Package created: $zipPath" -ForegroundColor Green
    
    # Show package contents
    Write-Host ""
    Write-Host "  Package Contents:" -ForegroundColor White
    $zipSize = (Get-Item $zipPath).Length / 1MB
    Write-Host "    Size: $([math]::Round($zipSize, 2)) MB" -ForegroundColor Gray
    Write-Host "    Files:" -ForegroundColor Gray
    Get-ChildItem $packageFolder | ForEach-Object {
        Write-Host "      - $($_.Name)" -ForegroundColor Gray
    }
    
} else {
    Write-Host ""
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host "[Step 5/5] Skipping Package Creation" -ForegroundColor Cyan
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor DarkGray
    Write-Host ""
    Write-Host "  Add --CreatePackage flag to create distribution ZIP" -ForegroundColor Yellow
}

# Summary
$EndTime = Get-Date
$Duration = $EndTime - $StartTime

Write-Host ""
Write-Host "????????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host "?                    BUILD SUMMARY                             ?" -ForegroundColor Green
Write-Host "????????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host ""

Write-Host "Build Time: $([math]::Round($Duration.TotalSeconds, 1)) seconds" -ForegroundColor White
Write-Host ""

if ($CSharpBuildSuccess) {
    Write-Host "? C# Application: SUCCESS" -ForegroundColor Green
} else {
    Write-Host "? C# Application: FAILED" -ForegroundColor Red
}

if ($Mode -eq "Full" -or $Mode -eq "Both") {
    if ($NativeBuildSuccess) {
        Write-Host "? Native DLL: SUCCESS" -ForegroundColor Green
    } else {
        Write-Host "? Native DLL: FAILED" -ForegroundColor Red
    }
}

Write-Host ""

if ($NativeBuildSuccess) {
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor Green
    Write-Host "  FULL SHADER MODE READY FOR DEPLOYMENT" -ForegroundColor Green
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor Green
    Write-Host ""
    Write-Host "Next Steps:" -ForegroundColor Cyan
    Write-Host "  1. Test the application: bin\Release\net8.0-windows\DisplayShadersPowerToy.exe" -ForegroundColor White
    Write-Host "  2. Run integration tests (as admin): .\test-integration.ps1" -ForegroundColor White
    Write-Host "  3. Sign binaries (optional): signtool sign ..." -ForegroundColor White
    Write-Host "  4. Create GitHub release with ZIP from dist\" -ForegroundColor White
} else {
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor Yellow
    Write-Host "  CLEARTYPE MODE READY FOR DEPLOYMENT" -ForegroundColor Yellow
    Write-Host "???????????????????????????????????????????????????" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "Next Steps:" -ForegroundColor Cyan
    Write-Host "  1. Test the application: bin\Release\net8.0-windows\DisplayShadersPowerToy.exe" -ForegroundColor White
    Write-Host "  2. Create GitHub release with ZIP from dist\" -ForegroundColor White
    Write-Host ""
    Write-Host "To enable Full Shader Mode:" -ForegroundColor Yellow
    Write-Host "  - Install Visual Studio 2022 with C++ Desktop Development workload" -ForegroundColor White
    Write-Host "  - Run: .\deploy-production.ps1 -Mode Full -CreatePackage" -ForegroundColor White
}

Write-Host ""
